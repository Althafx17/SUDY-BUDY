// Gemini AI Service for KTU Engineering Study Buddy
// Supports direct Gemini REST API with custom key or VITE_GEMINI_API_KEY

const API_KEY_STORAGE_KEY = 'orbit-gemini-api-key';

export function getGeminiApiKey() {
  try {
    return localStorage.getItem(API_KEY_STORAGE_KEY) || import.meta.env.VITE_GEMINI_API_KEY || '';
  } catch {
    return import.meta.env.VITE_GEMINI_API_KEY || '';
  }
}

export function saveGeminiApiKey(key) {
  try {
    if (key) {
      localStorage.setItem(API_KEY_STORAGE_KEY, key.trim());
    } else {
      localStorage.removeItem(API_KEY_STORAGE_KEY);
    }
  } catch {}
}

const KTU_SYSTEM_PROMPT = `You are an expert university professor and KTU (APJ Abdul Kalam Technological University, Kerala) Engineering academic tutor.
Your role is to solve and explain engineering examination questions thoroughly according to the KTU valuation scheme.

When asked to solve an exam question, structure your response clearly:
1. Given Information (with units)
2. Required Result / Objective
3. Governing Formulae, Theorems or Principles
4. Detailed Step-by-Step Working & Calculation (showing intermediate row operations, integration steps, substitutions)
5. Final Answer / Conclusion (bolded with units where applicable)
6. Common Exam Tips / Valuation Scheme Points

Keep explanations accurate, mathematically rigorous, and formatted with clear headings and bullet points.`;

/**
 * Call Gemini API to answer an engineering query or exam question
 */
export async function askGemini({ prompt, context, apiKey: overrideKey }) {
  const apiKey = overrideKey || getGeminiApiKey();

  if (!apiKey) {
    throw new Error('GEMINI_API_KEY_MISSING');
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`;

  let fullPrompt = prompt;
  if (context) {
    fullPrompt = `[Context: Subject: ${context.subject || 'KTU Engineering'}, Module: ${context.module || ''}, Topic: ${context.topic || ''}, Marks: ${context.marks || ''}]\n\nQuestion / Request:\n${prompt}`;
  }

  const payload = {
    contents: [
      {
        role: 'user',
        parts: [{ text: fullPrompt }]
      }
    ],
    systemInstruction: {
      parts: [{ text: KTU_SYSTEM_PROMPT }]
    },
    generationConfig: {
      temperature: 0.2,
      maxOutputTokens: 2500
    }
  };

  const res = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload)
  });

  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}));
    const message = errorData?.error?.message || `HTTP ${res.status}: ${res.statusText}`;
    throw new Error(message);
  }

  const data = await res.json();
  const candidate = data.candidates?.[0];
  const responseText = candidate?.content?.parts?.map(p => p.text).join('') || '';

  if (!responseText) {
    throw new Error('No answer generated by Gemini.');
  }

  return responseText;
}
